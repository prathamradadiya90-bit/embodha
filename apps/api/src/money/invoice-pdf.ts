import PDFDocument from 'pdfkit';

export interface TaxLine {
  /** CGST, SGST, UTGST or IGST. */
  name: string;
  rateBps: number;
  minor: number;
}

export interface InvoiceData {
  kind: 'invoice' | 'credit_note';
  number: string;
  date: string;
  /** A credit note names the invoice it reverses. */
  against?: { number: string; date: string };
  seller: { name: string; address: string; gstin: string; sac: string; state: string | null };
  buyer: { name: string | null; email: string; where: string | null };
  /** Karnataka is { code: '29', label: 'Karnataka (29)' }; exports are 96. Null on sales booked before it was kept. */
  placeOfSupply: { code: string; label: string } | null;
  item: string;
  currency: 'INR' | 'USD';
  grossMinor: number;
  gstMinor: number;
  gstRateBps: number;
  /** CGST and SGST, or IGST. Empty on old sales booked as one GST figure. */
  taxes: TaxLine[];
  note: string;
}

/** The built-in PDF fonts have no rupee sign, so amounts read "INR 846.61". */
const amount = (minor: number, currency: string) => `${currency} ${(minor / 100).toLocaleString('en-IN', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
const rate = (bps: number) => `${bps / 100}%`;

/**
 * One A4 page with what GST law asks an invoice or credit note to show: the seller and their GSTIN, a number and
 * date, the buyer, the place of supply, the taxable value, each tax at its rate, and whether reverse charge applies.
 */
export function renderInvoice(d: InvoiceData): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const credit = d.kind === 'credit_note';
    const title = credit ? 'Credit note' : d.seller.gstin ? 'Tax invoice' : 'Invoice';
    const doc = new PDFDocument({ size: 'A4', margin: 56, info: { Title: `${title} ${d.number}`, Author: d.seller.name } });
    const chunks: Buffer[] = [];
    doc.on('data', (chunk: Buffer) => chunks.push(chunk));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);

    doc.fillColor('#900201').fontSize(22).text(d.seller.name);
    doc.fillColor('#555555').fontSize(9);
    if (d.seller.address) doc.text(d.seller.address);
    if (d.seller.gstin) doc.text(`GSTIN ${d.seller.gstin}${d.seller.state ? `, ${d.seller.state}` : ''}`);

    doc.moveDown(2).fillColor('#231C19').fontSize(16).text(title);
    doc.moveDown(0.5).fontSize(10);
    const pair = (label: string, value: string) => {
      const y = doc.y;
      doc.font('Helvetica').fillColor('#555555').text(label, 56, y, { width: 130 });
      doc.fillColor('#231C19').text(value, 186, y, { width: 353 });
    };
    pair(credit ? 'Credit note number' : 'Invoice number', d.number);
    pair('Date', d.date);
    if (d.against) pair('Against invoice', `${d.against.number} of ${d.against.date}`);
    pair('Billed to', `${d.buyer.name ? `${d.buyer.name}, ` : ''}${d.buyer.email}`);
    if (d.buyer.where) pair(d.currency === 'INR' ? 'State' : 'Country', d.buyer.where);
    if (d.placeOfSupply) pair('Place of supply', d.placeOfSupply.label);
    if (d.seller.gstin) pair('Reverse charge', 'No');

    doc.moveDown(1.5).fillColor('#231C19').fontSize(11).text(d.item, 56, doc.y, { width: 483 });
    if (d.seller.sac) doc.fillColor('#555555').fontSize(9).text(`SAC ${d.seller.sac}`);
    doc.moveDown(0.6).fontSize(10);
    const row = (label: string, value: string, bold = false) => {
      const y = doc.y;
      doc.font(bold ? 'Helvetica-Bold' : 'Helvetica').fillColor('#231C19').text(label, 56, y, { width: 300 });
      doc.text(value, 356, y, { width: 183, align: 'right' });
    };
    const exported = d.placeOfSupply?.code === '96';
    if (d.gstMinor > 0 || exported || d.taxes.length) {
      row('Taxable value', amount(d.grossMinor - d.gstMinor, d.currency));
      if (d.taxes.length) for (const tax of d.taxes) row(`${tax.name} at ${rate(tax.rateBps)}`, amount(tax.minor, d.currency));
      else if (exported) row('IGST at 0% (export)', amount(0, d.currency));
      else row(`GST at ${rate(d.gstRateBps)}`, amount(d.gstMinor, d.currency));
    }
    row(credit ? 'Total credited' : 'Total paid', amount(d.grossMinor, d.currency), true);

    doc.moveDown(2).font('Helvetica').fillColor('#555555').fontSize(8);
    if (credit) doc.text('The full amount was refunded to the account it was paid from.', 56, doc.y, { width: 483 });
    if (d.note) doc.text(d.note, 56, doc.y, { width: 483 });
    doc.text(`This ${credit ? 'credit note' : 'invoice'} was generated by computer.`, 56, doc.y, { width: 483 });
    doc.end();
  });
}
